ACTION_VERB_BY_TIER = {1: "القيادة", 2: "القيادة", 3: "الإشراف", 4: "الإدارة التشغيلية"}


def _build_prompt(analysis: dict) -> str:
    tier = analysis["level_tier"]
    tone = TONE_BY_TIER[tier]
    domain = analysis["domain_name"]
    org_unit = analysis["org_unit_noun"]
    n_areas = "٢ إلى ٤" if tier <= 4 else "١ إلى ٣"
    return f"""أنت خبير موارد بشرية سعودي متخصص في كتابة بطاقات الوصف الوظيفي بالعربية الفصحى الرسمية.

المسمى الوظيفي: "{analysis['job_title']}"
المستوى الوظيفي (Tier {tier}): {analysis['level_label']}
الوحدة التنظيمية المرجعية: {org_unit} {domain}
نبرة الصياغة المطلوبة لهذا المستوى: {tone}

استند إلى الأطر المرجعية التالية دون اختلاق أرقام أو شهادات لا يمكن التحقق منها: {SOURCING_FRAMEWORKS}
عند التعارض أو غياب معلومة مؤكدة اختر الأكثر شيوعًا في السوق الخليجي/السعودي.

أنتج فقط كائن JSON صالح بالمفاتيح التالية، دون أي نص أو شرح خارج الـ JSON:
{{
  "job_purpose": "فقرة واحدة من 60 إلى 120 كلمة تلخص الغرض الأساسي من الوظيفة بالنبرة المطلوبة أعلاه، دون ذكر اسم منظمة فعلية (استخدم الإدارة/القطاع/المركز).",
  "specialized_responsibilities": [
    {{"category": "اسم مجال تخصصي دقيق ومحدد بمهام الوظيفة الفعلية", "duties": ["عبارة مسؤولية تفصيلية وقابلة للقياس، تذكر الأداة/المنهجية/المعيار عند الإمكان", "... (من 8 إلى 15 عبارة لكل مجال)"]}},
    "... ({n_areas} مجالات تخصصية رئيسية تغطي دورة العمل الكاملة للتخصص: التخطيط/التصميم، التطوير/التنفيذ، الجودة/الاختبار، الأمن/الامتثال، التشغيل/الصيانة، القياس والتحسين المستمر)"
  ],
  "qualifications": {{
    "education_required": "المؤهل العلمي الأدنى المطلوب (تخصص + درجة)",
    "education_preferred": "مؤهل أو شهادة مهنية مفضلة إضافية إن وجدت",
    "language_arabic": "المستوى المطلوب (مثال: متقدم)",
    "language_english": "المستوى المطلوب (مثال: متقدم)"
  }}
}}

تذكير: صياغة الأفعال في specialized_responsibilities يجب أن تتبع نفس نبرة المستوى {tier} أعلاه —
لا تستخدم أفعال قيادة/إشراف لوظائف المستويات 5-7."""


def _call_llm(prompt: str) -> dict:
    import anthropic

    client = anthropic.Anthropic(api_key=os.environ["ANTHROPIC_API_KEY"])
    model = os.environ.get("ANTHROPIC_MODEL", "claude-sonnet-5")
    message = client.messages.create(
        model=model,
        max_tokens=4096,
        messages=[{"role": "user", "content": prompt}],
    )
    text = "".join(block.text for block in message.content if getattr(block, "type", None) == "text")
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if not match:
        raise ValueError("لم يُرجع النموذج كائن JSON صالحًا")
    return json.loads(match.group(0))


